#!/usr/bin/env python3
"""Generate src/runtime/HadamardSigns.h: the fixed random signs of the KV rotation R = H_128 * diag(signs) / sqrt(128)
used by tools/reference/kv_ptq.py (torch.Generator seed 0, torch.randint(0, 2, (128,))). Run: python3 tools/reference/gen_hadamard_signs.py"""
import hashlib, os, sys
import torch
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kv_ptq
g = torch.Generator().manual_seed(0)
signs = [int(x) for x in (torch.randint(0, 2, (128,), generator=g) * 2 - 1).tolist()]
R = kv_ptq.hadamard()
H = torch.tensor([[1.0 if bin(i & j).count("1") % 2 == 0 else -1.0 for j in range(128)] for i in range(128)])
assert float((R - H * torch.tensor(signs, dtype=torch.float32)[None, :] / 128 ** 0.5).abs().max()) < 1e-7
h = hashlib.sha256(bytes((s + 1) // 2 for s in signs)).hexdigest()[:16]
out = ["// Generated by tools/reference/gen_hadamard_signs.py (sha256[:16] of sign bits: %s). Do not edit." % h,
       "#pragma once", "namespace tenzo {", "// R = H * diag(signs) / sqrt(128): y = signs .* FWHT(x) / sqrt(128)  (x @ R in kv_ptq.py)",
       "alignas(32) static const float kHadamardSigns128[128] = {"]
for i in range(0, 128, 16):
    out.append("    " + ", ".join("%+d.0f" % s for s in signs[i:i + 16]) + ",")
out += ["};", "} // namespace tenzo", ""]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "runtime", "HadamardSigns.h"), "w").write("\n".join(out))
print("ok", h)
