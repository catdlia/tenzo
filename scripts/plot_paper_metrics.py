#!/usr/bin/env python3
"""Plot measured native C++ attention latency from explicitly supplied CSVs.

Example:
  python scripts/plot_paper_metrics.py --csv 'Tab S11=tab_s11_metrics.csv' --output tab.png
The legacy CSV memory and bandwidth columns are deliberately ignored: their
formulas were incorrect. These measurements are attention calls, not generation.
Historical files without build/hardware provenance cannot establish new claims.
"""
import argparse
import csv
import math
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

def load_csv(path):
    rows = list(csv.DictReader(Path(path).open()))
    if not rows:
        raise ValueError(f'Empty measurement file: {path}')
    data = []
    for row in rows:
        context = int(row['context_length'])
        baseline = float(row['baseline_latency_ms'])
        packed = float(row['tenzo_latency_ms'])
        if context <= 0 or not all(math.isfinite(x) and x > 0 for x in (baseline, packed)):
            raise ValueError(f'Invalid measurement in {path}: {row}')
        data.append((context, baseline, packed))
    if len({r[0] for r in data}) != len(data):
        raise ValueError(f'Duplicate context in {path}')
    return sorted(data)

VARIANT_NAMES = {'a': 'a: FP32 + GQA copy', 'b': 'b: FP32 direct', 'c': 'c: INT8 KV direct', 'd': 'd: ternary packed KV direct'}


def load_ablation(path):
    """Rows of the four-variant schema (kind = timing | error). All numbers come from the CSV, none from this file."""
    rows = list(csv.DictReader(Path(path).open()))
    if not rows:
        raise ValueError(f'Empty ablation file: {path}')
    return rows


def ablation_report(path, out_prefix):
    rows = load_ablation(path)
    timing = [r for r in rows if r['kind'] == 'timing']
    errors = [r for r in rows if r['kind'] == 'error']
    key = lambda r: (int(r['Hq']), int(r['Hkv']), int(r['threads']))
    cfgs = sorted({key(r) for r in timing})
    gov = sorted({r['governor'] for r in rows})
    fig, axes = plt.subplots(2, len(cfgs), figsize=(4.2 * len(cfgs), 7), squeeze=False)
    md = ['# Attention ablation (generated by scripts/plot_paper_metrics.py from ' + str(path) + ')', '',
          'governor: ' + ', '.join(gov), '',
          '| geometry | threads | T | a ms | b ms | c ms | d ms | b/a | d/b | d/c | rss a MB | rss d MB |', '|---|---|---|---|---|---|---|---|---|---|---|---|']
    for ci, (hq, hkv, thr) in enumerate(cfgs):
        ax_lat, ax_rss = axes[0][ci], axes[1][ci]
        sel = [r for r in timing if key(r) == (hq, hkv, thr)]
        Ts = sorted({int(r['T']) for r in sel})
        table = {}
        for v in 'abcd':
            vr = {int(r['T']): r for r in sel if r['variant'] == v}
            xs = [t for t in Ts if t in vr]
            med = [float(vr[t]['median_ms']) for t in xs]
            lo = [float(vr[t]['median_ms']) - float(vr[t]['q1_ms']) for t in xs]
            hi = [float(vr[t]['q3_ms']) - float(vr[t]['median_ms']) for t in xs]
            ax_lat.errorbar(xs, med, yerr=[lo, hi], marker='o', capsize=2, label=VARIANT_NAMES[v])
            ax_rss.plot(xs, [float(vr[t]['hwm_kb']) / 1024 for t in xs], marker='s', label=VARIANT_NAMES[v])
            table[v] = vr
        ax_lat.set(title=f'{hq}Q/{hkv}KV, {thr} thread(s)', xlabel='context T', ylabel='median latency, ms (bars: IQR)', xscale='log', yscale='log')
        ax_rss.set(xlabel='context T', ylabel='process VmHWM, MiB', xscale='log', yscale='log')
        for ax in (ax_lat, ax_rss):
            ax.grid(alpha=.25)
        if ci == 0:
            ax_lat.legend(fontsize=7)
        for t in Ts:
            if all(t in table[v] for v in 'abcd'):
                m = {v: float(table[v][t]['median_ms']) for v in 'abcd'}
                md.append(f"| {hq}Q/{hkv}KV | {thr} | {t} | {m['a']:.3f} | {m['b']:.3f} | {m['c']:.3f} | {m['d']:.3f} | "
                          f"{m['b']/m['a']:.3f} | {m['d']/m['b']:.3f} | {m['d']/m['c']:.3f} | "
                          f"{float(table['a'][t]['hwm_kb'])/1024:.0f} | {float(table['d'][t]['hwm_kb'])/1024:.0f} |")
    md += ['', '## Output error relative to variant a (seeded Gaussian data, untimed)', '',
           '| geometry | T | variant | max_abs | rel_L2 | cosine |', '|---|---|---|---|---|---|']
    for r in sorted(errors, key=lambda r: (int(r['Hq']), int(r['T']), r['variant'])):
        md.append(f"| {r['Hq']}Q/{r['Hkv']}KV | {r['T']} | {r['variant']} | {float(r['err_max_abs']):.3e} | {float(r['err_rel_l2']):.3e} | {float(r['err_cosine']):.6f} |")
    fig.suptitle('Attention ablation (native C++, seeded Gaussian KV) - ' + ', '.join(gov))
    fig.tight_layout(); fig.savefig(out_prefix + '.png', dpi=160); plt.close(fig)
    Path(out_prefix + '.md').write_text('\n'.join(md) + '\n')
    print('wrote', out_prefix + '.png', out_prefix + '.md')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--csv', action='append', metavar='LABEL=PATH')
    parser.add_argument('--output')
    parser.add_argument('--ablation', metavar='CSV', help='four-variant ablation CSV (kind,variant,... schema)')
    parser.add_argument('--out-prefix', help='output prefix for --ablation (writes .png and .md)')
    args = parser.parse_args()
    if args.ablation:
        ablation_report(args.ablation, args.out_prefix or 'attn_ablation')
        return
    if not args.csv or not args.output:
        parser.error('--csv and --output are required without --ablation')
    fig, axes = plt.subplots(1, len(args.csv), figsize=(5 * len(args.csv), 4), squeeze=False)
    for ax, spec in zip(axes[0], args.csv):
        label, path = spec.split('=', 1)
        rows = load_csv(path)
        x = [r[0] for r in rows]
        ax.plot(x, [1000/r[1] for r in rows], 'o-', label='FP32 + per-head copy')
        ax.plot(x, [1000/r[2] for r in rows], 's-', label='Packed + direct indexing')
        ax.set(xlabel='Context length', ylabel='Attention invocations / s', title=label, xscale='log', yscale='log')
        ax.grid(alpha=.2); ax.legend()
    fig.suptitle('Native C++ synthetic attention — supplied historical CSVs')
    fig.tight_layout(); fig.savefig(args.output, dpi=180); plt.close(fig)

if __name__ == '__main__':
    main()
