#!/usr/bin/env python3
"""KV-mode perplexity v2 (after the 2026-11-19 engine fixes) vs golden fp32 and HF bf16, with last night's numbers.

Inputs (score-file format of `tenzo-inference --score-out`): --dir with <kv_mode>.txt, --golden, --hf, optional
--old-dir (2026-11-18 files, engine before the fixes). PPL = exp(sum nll / sum tokens) over windows.
95% CIs: bootstrap over windows (10000 draws, seed 0); delta/ratio CIs are paired (same resampled windows).
Every number in the outputs is computed here from the score files.
"""
import argparse, csv, math
from pathlib import Path
import numpy as np


def read(p):
    W = {}
    for line in Path(p).read_text().splitlines():
        if line.startswith('w '):
            _, i, n, nll = line.split(); W[int(i)] = (int(n), float(nll))
    return W


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dir', required=True); ap.add_argument('--golden', required=True); ap.add_argument('--hf', required=True)
    ap.add_argument('--old-dir', default=None); ap.add_argument('--out', required=True); ap.add_argument('--title', default='')
    ap.add_argument('--modes', default='fp32,int8_fused,tl1_fused,popcount_fused')
    a = ap.parse_args()
    G, H = read(a.golden), read(a.hf)
    rs = np.random.RandomState(0)
    rows = []
    for mode in a.modes.split(','):
        f = Path(a.dir) / (mode + '.txt')
        if not f.exists():
            rows.append({'kv_mode': mode, 'note': 'not measured'}); continue
        T = read(f)
        ids = sorted(set(T) & set(G) & set(H))
        old = read(Path(a.old_dir) / (mode + '.txt')) if a.old_dir and (Path(a.old_dir) / (mode + '.txt')).exists() else None
        arr = lambda W: (np.array([W[i][0] for i in ids], float), np.array([W[i][1] for i in ids], float))
        tn, tl = arr(T); gn, gl = arr(G); hn, hl = arr(H)
        P = lambda n, l, s=slice(None): math.exp(l[s].sum() / n[s].sum())
        boots = {'p': [], 'rg': [], 'rh': [], 'dg': [], 'dh': []}
        for _ in range(10000):
            s = rs.randint(0, len(ids), len(ids))
            p, pg, ph = P(tn, tl, s), P(gn, gl, s), P(hn, hl, s)
            boots['p'].append(p); boots['rg'].append(p / pg); boots['rh'].append(p / ph)
            boots['dg'].append(p - pg); boots['dh'].append(p - ph)
        ci = lambda k: (float(np.percentile(boots[k], 2.5)), float(np.percentile(boots[k], 97.5)))
        p, pg, ph = P(tn, tl), P(gn, gl), P(hn, hl)
        row = {'kv_mode': mode, 'windows': len(ids), 'ppl': p, 'ci_lo': ci('p')[0], 'ci_hi': ci('p')[1],
               'golden_fp32_ppl': pg, 'hf_bf16_ppl': ph,
               'delta_vs_golden': p - pg, 'delta_vs_golden_ci_lo': ci('dg')[0], 'delta_vs_golden_ci_hi': ci('dg')[1],
               'ratio_vs_golden': p / pg, 'ratio_vs_golden_ci_lo': ci('rg')[0], 'ratio_vs_golden_ci_hi': ci('rg')[1],
               'delta_vs_hf': p - ph, 'delta_vs_hf_ci_lo': ci('dh')[0], 'delta_vs_hf_ci_hi': ci('dh')[1],
               'ratio_vs_hf': p / ph, 'note': ''}
        if old is not None and all(i in old for i in ids):
            on, ol = np.array([old[i][0] for i in ids], float), np.array([old[i][1] for i in ids], float)
            row['ppl_2026_11_18'] = P(on, ol); row['ratio_vs_golden_2026_11_18'] = P(on, ol) / pg
        rows.append(row)
    keys = []
    for r in rows:
        for k in r:
            if k not in keys: keys.append(k)
    with open(a.out + '.csv', 'w', newline='') as fh:
        w = csv.DictWriter(fh, fieldnames=keys); w.writeheader(); w.writerows(rows)
    md = ['# %s' % (a.title or 'KV-mode perplexity v2'), '',
          'Generated by scripts/analyze_kv_ppl_v2.py. 95% CIs: bootstrap over windows (10000, seed 0), paired for deltas/ratios.', '',
          '| kv mode | windows | PPL | 95% CI | delta_vs_golden [CI] | ratio vs golden fp32 [CI] | delta_vs_hf [CI] | PPL 2026-11-18 (before fixes) | ratio vs golden 2026-11-18 |',
          '|---|---|---|---|---|---|---|---|---|']
    for r in rows:
        if 'ppl' not in r:
            md.append('| %s | - | not measured | | | | | | |' % r['kv_mode']); continue
        md.append('| %s | %d | %.3f | [%.3f, %.3f] | %+.3f [%+.3f, %+.3f] | %.4f [%.4f, %.4f] | %+.3f [%+.3f, %+.3f] | %s | %s |' % (
            r['kv_mode'], r['windows'], r['ppl'], r['ci_lo'], r['ci_hi'], r['delta_vs_golden'], r['delta_vs_golden_ci_lo'],
            r['delta_vs_golden_ci_hi'], r['ratio_vs_golden'], r['ratio_vs_golden_ci_lo'], r['ratio_vs_golden_ci_hi'],
            r['delta_vs_hf'], r['delta_vs_hf_ci_lo'], r['delta_vs_hf_ci_hi'],
            '%.3f' % r['ppl_2026_11_18'] if 'ppl_2026_11_18' in r else '-',
            '%.3f' % r['ratio_vs_golden_2026_11_18'] if 'ratio_vs_golden_2026_11_18' in r else '-'))
    r0 = next((r for r in rows if 'ppl' in r), None)
    if r0:
        md += ['', 'References on the same windows: golden fp32 PPL %.3f, HF bf16 PPL %.3f.' % (r0['golden_fp32_ppl'], r0['hf_bf16_ppl'])]
    Path(a.out + '.md').write_text('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
