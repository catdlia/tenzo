#!/usr/bin/env python3
"""Calibration / language-disparity analysis (part 2, block 2.6) from golden-framework score files.

For every scheme S and language L (EN: 16 windows, UK: 32 windows, 511 scored tokens each):
  PPL(S), ratio PPL(S)/PPL(golden fp32-KV) with a paired bootstrap CI over windows,
  dNLL(S) = mean over windows of [NLL_w(S) - NLL_w(golden)] per token, in nats, with a bootstrap CI,
  within-language regression dNLL_w = a + b * NLL0_w  (NLL0_w = golden per-token NLL of window w; "text difficulty").
Pooled model over EN and UK windows:  dNLL_w = a + b * NLL0_w + c * UK_w.
  c is the extra degradation of Ukrainian at equal base difficulty; its 95% CI comes from a bootstrap that resamples windows
  inside each language (10000 draws, seed 0). If the CI of c contains 0 the disparity is explained by difficulty alone.
Output: PREFIX.csv, PREFIX.md, PREFIX_scatter.png (all numbers computed here from the score files).

Usage: analyze_kv_calib.py --golden-en G --golden-uk G --out PREFIX  NAME=EN_FILE,UK_FILE [NAME=EN_FILE,UK_FILE ...]
"""
import argparse, csv, math
from pathlib import Path
import numpy as np


def rd(p):
    W = {}
    for line in open(p):
        if line.startswith("w "):
            _, i, n, x = line.split(); W[int(i)] = (int(n), float(x))
    return W


def per_win(T, G, ids):
    n = np.array([T[i][0] for i in ids], float)
    return n, np.array([T[i][1] for i in ids]) / n, np.array([G[i][1] for i in ids]) / n  # tokens, nll/token, base nll/token


def ols(x, y):
    A = np.vstack([np.ones_like(x), x]).T
    coef, *_ = np.linalg.lstsq(A, y, rcond=None)
    res = y - A @ coef
    r2 = 1 - (res ** 2).sum() / max(((y - y.mean()) ** 2).sum(), 1e-30)
    return coef[0], coef[1], r2


def pooled_c(x_en, y_en, x_uk, y_uk):
    x = np.concatenate([x_en, x_uk]); y = np.concatenate([y_en, y_uk]); d = np.concatenate([np.zeros(len(x_en)), np.ones(len(x_uk))])
    A = np.vstack([np.ones_like(x), x, d]).T
    return np.linalg.lstsq(A, y, rcond=None)[0]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--golden-en", required=True); ap.add_argument("--golden-uk", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("schemes", nargs="+")
    a = ap.parse_args()
    GE, GU = rd(a.golden_en), rd(a.golden_uk)
    rs = np.random.RandomState(0)
    rows = []
    for spec in a.schemes:
        name, files = spec.split("=", 1); fe, fu = files.split(",")
        TE, TU = rd(fe), rd(fu)
        ie, iu = sorted(set(TE) & set(GE)), sorted(set(TU) & set(GU))
        ne, le, be = per_win(TE, GE, ie); nu, lu, bu = per_win(TU, GU, iu)
        de, du = le - be, lu - bu
        draws = []
        for _ in range(10000):
            se, su = rs.randint(0, len(ie), len(ie)), rs.randint(0, len(iu), len(iu))
            c = pooled_c(be[se], de[se], bu[su], du[su])[2]
            draws.append((np.exp(le[se].mean()) / np.exp(be[se].mean()), np.exp(lu[su].mean()) / np.exp(bu[su].mean()),
                          de[se].mean(), du[su].mean(), c))
        draws = np.array(draws); q = lambda col: (np.percentile(draws[:, col], 2.5), np.percentile(draws[:, col], 97.5))
        coef = pooled_c(be, de, bu, du)
        for lang, n, l, b, d, col_r, col_d in (("en", ne, le, be, de, 0, 2), ("uk", nu, lu, bu, du, 1, 3)):
            ia, ib, r2 = ols(b, d)
            rr = q(col_r); dd = q(col_d)
            rows.append(dict(scheme=name, lang=lang, windows=len(d), ppl=math.exp(l.mean()), golden_ppl=math.exp(b.mean()),
                             ratio=math.exp(l.mean()) / math.exp(b.mean()), ratio_ci_lo=rr[0], ratio_ci_hi=rr[1],
                             dnll=d.mean(), dnll_ci_lo=dd[0], dnll_ci_hi=dd[1], base_nll=b.mean(),
                             reg_intercept=ia, reg_slope=ib, reg_r2=r2, pooled_a=coef[0], pooled_b=coef[1], pooled_c_uk=coef[2],
                             pooled_c_ci_lo=q(4)[0], pooled_c_ci_hi=q(4)[1]))
    keys = list(rows[0].keys())
    with open(a.out + ".csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys); w.writeheader(); w.writerows(rows)
    L = ["# Calibrated ternary KV and language disparity (BitNet-b1.58-2B-4T, golden fp32 + fake-quant)", "",
         "Generated by scripts/analyze_kv_calib.py. dNLL = per-token NLL(scheme) - NLL(golden fp32-KV), nats, mean over windows with 95% bootstrap CI.",
         "Regression: dNLL_w = a + b * NLL0_w within a language; pooled: dNLL_w = a + b * NLL0_w + c * UK. c = extra Ukrainian degradation at equal base difficulty.", "",
         "| scheme | lang | windows | PPL | ratio vs golden [95% CI] | dNLL [95% CI] | base NLL | slope b (R2) | pooled c_UK [95% CI] |",
         "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append("| %s | %s | %d | %.2f | %.4f [%.4f, %.4f] | %+.4f [%+.4f, %+.4f] | %.3f | %+.3f (%.2f) | %+.4f [%+.4f, %+.4f] |" % (
            r["scheme"], r["lang"], r["windows"], r["ppl"], r["ratio"], r["ratio_ci_lo"], r["ratio_ci_hi"], r["dnll"], r["dnll_ci_lo"],
            r["dnll_ci_hi"], r["base_nll"], r["reg_slope"], r["reg_r2"], r["pooled_c_uk"], r["pooled_c_ci_lo"], r["pooled_c_ci_hi"]))
    Path(a.out + ".md").write_text("\n".join(L) + "\n")
    print("\n".join(L))
    try:
        import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
        names = [s.split("=")[0] for s in a.schemes]
        fig, axes = plt.subplots(1, len(names), figsize=(4.2 * len(names), 3.8), squeeze=False)
        for ax, spec in zip(axes[0], a.schemes):
            name, files = spec.split("=", 1); fe, fu = files.split(",")
            for lang, T, G, col in (("EN", rd(fe), GE, "tab:blue"), ("UK", rd(fu), GU, "tab:orange")):
                ids = sorted(set(T) & set(G)); n, l, b = per_win(T, G, ids)
                ax.scatter(b, l - b, s=14, c=col, label=lang)
                ia, ib, _ = ols(b, l - b); xs = np.linspace(b.min(), b.max(), 20); ax.plot(xs, ia + ib * xs, c=col, lw=1)
            ax.set_title(name, fontsize=8); ax.set_xlabel("window NLL, golden fp32 (nats/token)"); ax.set_ylabel("dNLL (nats/token)")
            ax.legend(fontsize=7)
        fig.tight_layout(); fig.savefig(a.out + "_scatter.png", dpi=120)
    except Exception as e:
        print("plot skipped:", e)


if __name__ == "__main__":
    main()
