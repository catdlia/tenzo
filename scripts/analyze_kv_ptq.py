#!/usr/bin/env python3
"""Block D: ternary-KV PTQ study table + Pareto plot (bits/element vs dPPL), all derived from golden score files.

Usage: analyze_kv_ptq.py --screen DIR --golden GOLDEN.txt [--final-en DIR --golden-en G.txt --final-uk DIR --golden-uk G.txt]
       --out PREFIX
Screening: PPL over the windows present in each file vs golden fp32 on the same windows (no CI: 4 windows).
Finalists: PPL with 95% bootstrap CI and paired ratio CI vs golden (10000 draws, seed 0).
Bits: tools/reference/kv_ptq.bits() at ctx 512 and asymptotically (ternary stored as 2-bit codes, fp16 scales)."""
import argparse, csv, glob, math, os, sys
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools", "reference"))
import kv_ptq  # noqa: E402


def rd(p):
    W = {}
    for line in open(p):
        if line.startswith("w "):
            _, i, n, x = line.split(); W[int(i)] = (int(n), float(x))
    return W


def name_of(f):
    n = os.path.basename(f)[:-4]
    if n.startswith("K8V_"): return "K8V:" + n[4:]
    if n.startswith("KV8_"): return "KV8:" + n[4:]
    return n.replace("_s", "+s", 1) if "_s" in n and n.split("_s")[1][:1].isdigit() else n


def ppl(W, ids): return math.exp(sum(W[i][1] for i in ids) / sum(W[i][0] for i in ids))


def boot(T, G, ids, draws=10000):
    rs = np.random.RandomState(0); tn = np.array([T[i][0] for i in ids]); tl = np.array([T[i][1] for i in ids])
    gl = np.array([G[i][1] for i in ids]); gn = np.array([G[i][0] for i in ids]); P, Rr = [], []
    for _ in range(draws):
        s = rs.randint(0, len(ids), len(ids)); a = math.exp(tl[s].sum() / tn[s].sum()); b = math.exp(gl[s].sum() / gn[s].sum())
        P.append(a); Rr.append(a / b)
    q = lambda v: (np.percentile(v, 2.5), np.percentile(v, 97.5))
    return q(P), q(Rr)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--screen", required=True); ap.add_argument("--golden", required=True)
    ap.add_argument("--final-en", default=None); ap.add_argument("--golden-en", default=None)
    ap.add_argument("--final-uk", default=None); ap.add_argument("--golden-uk", default=None)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    G = rd(a.golden); rows = []
    for f in sorted(glob.glob(os.path.join(a.screen, "*.txt"))):
        if "progress" in f: continue
        T = rd(f); ids = sorted(T); n = name_of(f)
        if not ids: continue
        p, g = ppl(T, ids), ppl(G, ids)
        rows.append(dict(stage="screen", scheme=n, lang="en", windows=len(ids), ppl=p, golden_ppl=g, dppl_pct=100 * (p / g - 1),
                         ci_lo="", ci_hi="", ratio_ci_lo="", ratio_ci_hi="", bits_ctx512=kv_ptq.bits(n, 512),
                         bits_asym=kv_ptq.bits(n), desc=kv_ptq.resolve(n)[5]))
    for stage_dir, gpath, lang in ((a.final_en, a.golden_en, "en"), (a.final_uk, a.golden_uk, "uk")):
        if not stage_dir: continue
        GG = rd(gpath)
        for f in sorted(glob.glob(os.path.join(stage_dir, "*.txt"))):
            if "progress" in f: continue
            T = rd(f); ids = sorted(T); n = name_of(f)
            if not ids: continue
            (lo, hi), (rlo, rhi) = boot(T, GG, ids)
            p, g = ppl(T, ids), ppl(GG, ids)
            rows.append(dict(stage="final", scheme=n, lang=lang, windows=len(ids), ppl=p, golden_ppl=g, dppl_pct=100 * (p / g - 1),
                             ci_lo=lo, ci_hi=hi, ratio_ci_lo=rlo, ratio_ci_hi=rhi, bits_ctx512=kv_ptq.bits(n, 512),
                             bits_asym=kv_ptq.bits(n), desc=kv_ptq.resolve(n)[5]))
    with open(a.out + ".csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
    L = ["# Ternary KV PTQ study (golden fp32 + KV fake-quant, no retraining)", "",
         "Generated by scripts/analyze_kv_ptq.py from score files in kv_ptq/. dPPL relative to golden fp32-KV on the same windows.", "",
         "| stage | lang | scheme | windows | PPL | golden | dPPL | 95% CI of PPL/golden | bits@512 | bits asymptotic | description |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        ci = "[%.3f, %.3f]" % (r["ratio_ci_lo"], r["ratio_ci_hi"]) if r["ratio_ci_lo"] != "" else "-"
        L.append("| %s | %s | %s | %d | %.3f | %.3f | %+.1f%% | %s | %.3f | %.3f | %s |" % (r["stage"], r["lang"], r["scheme"], r["windows"],
                 r["ppl"], r["golden_ppl"], r["dppl_pct"], ci, r["bits_ctx512"], r["bits_asym"], r["desc"]))
    open(a.out + ".md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))
    try:
        import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(7.5, 4.8))
        sc = [r for r in rows if r["stage"] == "screen" and r["scheme"] != "fp32"]
        ax.scatter([r["bits_ctx512"] for r in sc], [max(r["dppl_pct"], 0.1) for r in sc], c="tab:blue", label="screening (4 EN windows)")
        for r in sc:
            ax.annotate(r["scheme"], (r["bits_ctx512"], max(r["dppl_pct"], 0.1)), fontsize=7, xytext=(3, 3), textcoords="offset points")
        fe = [r for r in rows if r["stage"] == "final"]
        for lang, col in (("en", "tab:red"), ("uk", "tab:green")):
            pts = [r for r in fe if r["lang"] == lang]
            if pts:
                ax.scatter([r["bits_ctx512"] for r in pts], [max(r["dppl_pct"], 0.1) for r in pts], marker="s", c=col,
                           label="finalists, %s (%d windows)" % (lang.upper(), pts[0]["windows"]))
        ax.axhline(5, color="gray", ls="--", lw=0.8); ax.axvline(2.5, color="gray", ls=":", lw=0.8)
        ax.set_yscale("log"); ax.set_xlabel("effective bits per K/V element at ctx 512 (incl. scales, INT8 windows)")
        ax.set_ylabel("dPPL vs golden fp32-KV, % (log)"); ax.set_title("Ternary KV PTQ: bits vs quality")
        ax.legend(fontsize=7); fig.tight_layout(); fig.savefig(a.out + ".png", dpi=120)
    except Exception as e:
        print("plot skipped:", e)


if __name__ == "__main__":
    main()
