#!/usr/bin/env python3
"""Generate src/runtime/UnicodeTables.h for the Tenzo Llama-3 BPE pre-tokenizer.

Tables cover:
  - \\p{L}: Unicode General_Category L* (Lu, Ll, Lt, Lm, Lo)
  - \\p{N}: Unicode General_Category N* (Nd, Nl, No)
  - \\s  : Unicode White_Space (25 codepoints, matching HF tokenizers Split regex)
"""

from __future__ import annotations

import pathlib
import unicodedata


WHITE_SPACE_25 = sorted(
    [
        0x0009, 0x000A, 0x000B, 0x000C, 0x000D,
        0x0020, 0x0085, 0x00A0, 0x1680,
        *range(0x2000, 0x200B),
        0x2028, 0x2029, 0x202F, 0x205F, 0x3000,
    ]
)


def collect_ranges(pred) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    start: int | None = None
    prev: int | None = None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            hit = False
        else:
            hit = pred(cp)
        if hit:
            if start is None:
                start = cp
            elif prev is not None and cp != prev + 1:
                ranges.append((start, prev))
                start = cp
            prev = cp
        else:
            if start is not None and prev is not None:
                ranges.append((start, prev))
                start = None
                prev = None
    if start is not None and prev is not None:
        ranges.append((start, prev))
    return ranges


def format_ranges(name: str, ranges: list[tuple[int, int]]) -> str:
    lines = [f"static constexpr UnicodeRange {name}[] = {{"]
    for i in range(0, len(ranges), 4):
        chunk = ", ".join(f"{{0x{a:06X}u, 0x{b:06X}u}}" for a, b in ranges[i : i + 4])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    l_ranges = collect_ranges(lambda cp: unicodedata.category(chr(cp)).startswith("L"))
    n_ranges = collect_ranges(lambda cp: unicodedata.category(chr(cp)).startswith("N"))

    root = pathlib.Path(__file__).resolve().parents[2]
    out_path = root / "src" / "runtime" / "UnicodeTables.h"

    ws_items = ", ".join(f"0x{cp:04X}u" for cp in WHITE_SPACE_25)
    content = f"""#pragma once
// Auto-generated by tools/tokenizer/gen_unicode_tables.py (Unicode {unicodedata.unidata_version}).
// Provides exact \\p{{L}}, \\p{{N}}, and \\s (White_Space) classification matching HF tokenizers.

#include <algorithm>
#include <cstddef>
#include <cstdint>

namespace tenzo {{
namespace runtime {{
namespace detail {{

struct UnicodeRange {{
    uint32_t lo;
    uint32_t hi;
}};

{format_ranges("kUnicodeLetterRanges", l_ranges)}

{format_ranges("kUnicodeNumberRanges", n_ranges)}

static constexpr uint32_t kUnicodeWhiteSpace[] = {{
    {ws_items}
}};

inline bool in_unicode_ranges(uint32_t cp, const UnicodeRange* ranges, size_t count) {{
    size_t lo = 0, hi = count;
    while (lo < hi) {{
        size_t mid = lo + (hi - lo) / 2;
        if (cp < ranges[mid].lo) {{
            hi = mid;
        }} else if (cp > ranges[mid].hi) {{
            lo = mid + 1;
        }} else {{
            return true;
        }}
    }}
    return false;
}}

inline bool is_unicode_letter(uint32_t cp) {{
    if (cp < 0x80u) {{
        return (cp >= 'A' && cp <= 'Z') || (cp >= 'a' && cp <= 'z');
    }}
    return in_unicode_ranges(cp, kUnicodeLetterRanges,
                             sizeof(kUnicodeLetterRanges) / sizeof(kUnicodeLetterRanges[0]));
}}

inline bool is_unicode_number(uint32_t cp) {{
    if (cp < 0x80u) {{
        return cp >= '0' && cp <= '9';
    }}
    return in_unicode_ranges(cp, kUnicodeNumberRanges,
                             sizeof(kUnicodeNumberRanges) / sizeof(kUnicodeNumberRanges[0]));
}}

inline bool is_unicode_space(uint32_t cp) {{
    if (cp < 0x80u) {{
        return cp == ' ' || (cp >= 0x09u && cp <= 0x0Du);
    }}
    for (uint32_t ws : kUnicodeWhiteSpace) {{
        if (cp == ws) return true;
        if (cp < ws) break;
    }}
    return false;
}}

}} // namespace detail
}} // namespace runtime
}} // namespace tenzo
"""
    out_path.write_text(content, encoding="utf-8")
    print(f"Wrote {out_path} ({len(l_ranges)} L ranges, {len(n_ranges)} N ranges, {len(WHITE_SPACE_25)} WS codepoints)")


if __name__ == "__main__":
    main()
