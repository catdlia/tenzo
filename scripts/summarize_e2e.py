#!/usr/bin/env python3
"""Summarise e2e_fair.csv (written by scripts/run_e2e_fair.py) into a markdown table: medians over repetitions, plus min-max. No constants."""
import csv, collections, statistics as st, sys
src, out = sys.argv[1], sys.argv[2]
rows = [r for r in csv.DictReader(open(src))]
g = collections.defaultdict(list)
for r in rows:
    if not r["note"].startswith("UNSUPPORTED"): g[(int(r["prompt_len"]), r["engine"], r["kv"])].append(r)
gov = sorted({r["governor"] for r in rows})
def med(rs, f):
    v = [float(x[f]) for x in rs if x[f]]
    return (st.median(v), min(v), max(v)) if v else None
fmt = lambda t, d=1: "-" if t is None else f"{t[0]:.{d}f} ({t[1]:.{d}f}-{t[2]:.{d}f})"
KVNOTE = {("tenzo", "fp32"): "fp32 KV", ("tenzo", "int8_fused"): "int8 per-token-scaled KV", ("tenzo", "tl1_fused"): "2-bit ternary KV (lossy, see ppl_kv.md)",
          ("bitnet.cpp", "f16"): "f16 KV (default)", ("bitnet.cpp", "q8_0"): "q8_0 KV (flash-attn on)"}
md = ["# Fair end-to-end comparison on the laptop (generated by scripts/summarize_e2e.py from e2e_fair.csv)", "",
      f"i3-1215U, 4 threads pinned to cpus 0-3 for both engines, governor: {', '.join(gov)}, 128 generated tokens, greedy, {len(next(iter(g.values())))} repetitions, "
      "median (min-max). Tenzo ran in the dev container, bitnet.cpp (llama-bench) on the host. Nothing else was running.", "",
      "| prompt | engine | KV cache | pp tok/s | tg tok/s | prompt+gen tok/s (like-for-like) | peak RSS MB | KV note |", "|---|---|---|---|---|---|---|---|"]
for k in sorted(g):
    rs = g[k]
    md.append(f"| {k[0]} | {k[1]} | {k[2]} | {fmt(med(rs,'pp_tps'))} | {fmt(med(rs,'tg_tps'))} | {fmt(med(rs,'pg_tps'))} | {fmt(med(rs,'rss_mb'),0)} | {KVNOTE.get((k[1],k[2]),'')} |")
md += ["", "## Reading it honestly",
       "* `pp` : Tenzo prefills token by token (no batching); llama.cpp processes the prompt as one batch, so pp is not like-for-like in method, only in outcome.",
       "* `tg` : Tenzo decodes AFTER the prompt (attention over prompt+generated tokens); llama-bench `-n` decodes from an EMPTY context. The like-for-like column is prompt+gen (llama-bench `-pg`).",
       "* KV modes do not correspond: f16/q8_0 (llama.cpp) vs fp32/int8/ternary (Tenzo). No row pair has identical KV precision.",
       "* RSS: Tenzo VmHWM from /proc/self/status at exit (includes the transient embedding/weights conversion at load), llama-bench peak VmHWM polled from /proc. Both are process peaks, not KV-only.",
       "* The local bitnet.cpp build computes a numerically different model (WikiText-2 PPL 102 vs 19 for HF, see ppl_kv.md), so its throughput is the speed of that build, not evidence about a correct BitNet pipeline."]
open(out, "w").write("\n".join(md) + "\n"); print("\n".join(md[:30]))
