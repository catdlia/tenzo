#!/usr/bin/env python3
"""Perplexity per KV mode with 95% bootstrap CIs over windows, plus difference vs fp32 (paired bootstrap).

Inputs: score files written by `tenzo-inference --score ... --score-out` (and the HF / libllama references, same text format):
  '# ...' header, then per window:  'w <idx> <n_tokens> <sum_nll>'  and  'lp <logprob per token ...>'.
PPL of a set of windows = exp(sum nll / sum tokens). Bootstrap: resample windows with replacement (seed 0, 10000 draws).
Outputs ppl_kv.csv and ppl_kv.md; every number is derived from the score files (no constants in this script).
"""
import argparse, csv, json, math, sys
from pathlib import Path
import numpy as np


def read_scores(path):
    wins = {}
    cur = None
    for line in Path(path).read_text().splitlines():
        if line.startswith('w '):
            _, idx, n, nll = line.split()
            cur = int(idx); wins[cur] = {'n': int(n), 'nll': float(nll), 'lp': None}
        elif line.startswith('lp ') and cur is not None:
            wins[cur]['lp'] = np.array([float(x) for x in line.split()[1:]], dtype=np.float64)
    return wins


def ppl(ws, idx):
    n = sum(ws[i]['n'] for i in idx); nll = sum(ws[i]['nll'] for i in idx)
    return math.exp(nll / n)


def boot(ws_a, ws_b, ids, draws=10000, seed=0):
    rs = np.random.RandomState(seed)
    nl_a = np.array([ws_a[i]['nll'] for i in ids]); n_a = np.array([ws_a[i]['n'] for i in ids])
    out_a, out_d = [], []
    if ws_b is not None:
        nl_b = np.array([ws_b[i]['nll'] for i in ids]); n_b = np.array([ws_b[i]['n'] for i in ids])
    for _ in range(draws):
        s = rs.randint(0, len(ids), len(ids))
        pa = math.exp(nl_a[s].sum() / n_a[s].sum()); out_a.append(pa)
        if ws_b is not None:
            out_d.append(pa - math.exp(nl_b[s].sum() / n_b[s].sum()))
    ci = lambda v: (float(np.percentile(v, 2.5)), float(np.percentile(v, 97.5)))
    return ci(out_a), (ci(out_d) if ws_b is not None else None)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dir', required=True, help='directory holding <label>.txt score files')
    ap.add_argument('--baseline', default='fp32')
    ap.add_argument('--hf', default=None, help='HF reference score file (ground truth NLL)')
    ap.add_argument('--llama', default=None, help='libllama (bitnet.cpp) score file')
    ap.add_argument('--out', required=True, help='output prefix')
    ap.add_argument('--dataset', default='WikiText-2 (raw test), 16 windows chosen with numpy RandomState(0)')
    ap.add_argument('--mem', default=None, help='JSON {mode: {"kv_bytes_per_token":..., "rss_kb_ctx8192":...}}')
    a = ap.parse_args()
    files = {p.stem: read_scores(p) for p in sorted(Path(a.dir).glob('*.txt'))}
    files = {k: v for k, v in files.items() if v}          # ignore non-score files such as progress.txt
    refs = {}
    if a.hf: refs['hf_bf16'] = read_scores(a.hf)
    if a.llama: refs['bitnet_cpp_i2s'] = read_scores(a.llama)
    allsets = {**refs, **files}
    ids = sorted(set.intersection(*[set(w) for w in allsets.values()]))
    base = files.get(a.baseline)
    mem = json.loads(Path(a.mem).read_text()) if a.mem else {}
    rows = []
    for name, ws in allsets.items():
        p = ppl(ws, ids); ci, dci = boot(ws, base, ids)
        row = {'label': name, 'windows': len(ids), 'tokens': sum(ws[i]['n'] for i in ids), 'ppl': p, 'ci95_lo': ci[0], 'ci95_hi': ci[1],
               'delta_vs_fp32': (p - ppl(base, ids)) if base is not None else '',
               'delta_ci95_lo': dci[0] if dci else '', 'delta_ci95_hi': dci[1] if dci else '',
               'kv_bytes_per_token': mem.get(name, {}).get('kv_bytes_per_token', ''), 'rss_kb_ctx8192': mem.get(name, {}).get('rss_kb_ctx8192', '')}
        # per-token agreement with the HF ground truth (same tokens)
        if 'hf_bf16' in refs and name != 'hf_bf16' and all(ws[i]['lp'] is not None and refs['hf_bf16'][i]['lp'] is not None for i in ids):
            d = np.concatenate([ws[i]['lp'] - refs['hf_bf16'][i]['lp'] for i in ids])
            row['mean_abs_dlogp_vs_hf'] = float(np.abs(d).mean()); row['mean_dlogp_vs_hf'] = float(d.mean())
        rows.append(row)
    keys = []
    for r in rows:
        for k in r:
            if k not in keys: keys.append(k)
    with open(a.out + '.csv', 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=keys); w.writeheader(); w.writerows(rows)
    md = ['# KV-mode perplexity (generated by scripts/analyze_kv_ppl.py)', '',
          f'{len(ids)} fixed windows x 512 tokens (BOS + 511 text tokens, 511 scored each); dataset: {a.dataset}. 95% CI = bootstrap over windows (10000 draws, seed 0).', '',
          '| engine / kv mode | PPL | 95% CI | dPPL vs tenzo fp32 | 95% CI of d | mean abs dlogp vs HF | KV bytes/token | RSS KB (ctx 8192) |', '|---|---|---|---|---|---|---|---|']
    for r in rows:
        fmt = lambda x, f='{:.3f}': (f.format(x) if isinstance(x, float) else (x if x != '' else '-'))
        md.append(f"| {r['label']} | {r['ppl']:.3f} | [{r['ci95_lo']:.3f}, {r['ci95_hi']:.3f}] | {fmt(r['delta_vs_fp32'])} | "
                  f"{'[%.3f, %.3f]' % (r['delta_ci95_lo'], r['delta_ci95_hi']) if r['delta_ci95_lo'] != '' else '-'} | "
                  f"{fmt(r.get('mean_abs_dlogp_vs_hf', '-'), '{:.4f}')} | {r['kv_bytes_per_token'] or '-'} | {r['rss_kb_ctx8192'] or '-'} |")
    Path(a.out + '.md').write_text('\n'.join(md) + '\n')
    print('\n'.join(md))


if __name__ == '__main__':
    main()
