#!/usr/bin/env python3
"""RSS breakdown by mapping from /proc/self/smaps dumps (TENZO_SMAPS_DIR of tenzo-inference).
Usage: analyze_smaps.py OUT.md TAG=path.smaps [TAG=path.smaps ...]   (rollup files, when present next to a .smaps, are quoted too)
Categories: anonymous heap/arena (anon, [heap]), file-backed (weights.bin mapping, shared libraries), stack, other."""
import re, sys
out, specs = sys.argv[1], sys.argv[2:]
hdr = re.compile(r"^[0-9a-f]+-[0-9a-f]+ \S+ \S+ \S+ \S+\s*(.*)$")


def parse(path):
    maps, cur = [], None
    for line in open(path):
        m = hdr.match(line)
        if m:
            cur = {"name": m.group(1).strip() or "[anon]", "Rss": 0, "Pss": 0, "Anonymous": 0, "Size": 0}
            maps.append(cur)
        elif cur is not None:
            k, _, v = line.partition(":")
            if k in ("Rss", "Pss", "Anonymous", "Size"):
                cur[k] = int(v.split()[0])
    return maps


def category(name):
    if name.endswith("weights.bin"): return "weights.bin (file mapping)"
    if name.startswith("[heap]") or name == "[anon]": return "anonymous (heap/arenas/vectors)"
    if name.startswith("[stack"): return "stack"
    if ".so" in name: return "shared libraries"
    return "other (" + name.split("/")[-1][:30] + ")"


L = ["# RSS breakdown by mapping", "", "Generated by scripts/analyze_smaps.py from /proc/self/smaps dumps. Values in MB (Rss), summed per category.", ""]
tags = []
tables = {}
for sp in specs:
    tag, path = sp.split("=", 1)
    tags.append(tag)
    agg = {}
    for m in parse(path):
        c = category(m["name"]); agg[c] = agg.get(c, 0) + m["Rss"]
    tables[tag] = agg
cats = sorted({c for a in tables.values() for c in a}, key=lambda c: -max(a.get(c, 0) for a in tables.values()))
L.append("| category | " + " | ".join(tags) + " |")
L.append("|---|" + "---|" * len(tags))
for c in cats:
    L.append("| %s | %s |" % (c, " | ".join("%.0f" % (tables[t].get(c, 0) / 1024) for t in tags)))
L.append("| **total Rss** | %s |" % " | ".join("**%.0f**" % (sum(tables[t].values()) / 1024) for t in tags))
open(out, "w").write("\n".join(L) + "\n")
print("\n".join(L))
